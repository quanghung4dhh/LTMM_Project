
"""Classical transposition cipher implementations."""

from __future__ import annotations

from collections.abc import Sequence

from src.mathematics.permutation import (
    validate_permutation,
    inverse_permutation,
)


def _validate_text(text: str, name: str) -> None:
    """Validate that the input text is a string.

    Args:
        text: Plaintext or ciphertext.
        name: Parameter name used in the error message.

    Raises:
        TypeError: If text is not a string.
    """
    if not isinstance(text, str):
        raise TypeError(
            f"{name} must be a string, got {type(text).__name__}"
        )


def _validate_rails(rails: int) -> None:
    """Validate the number of rails.

    Args:
        rails: Number of rails.

    Raises:
        TypeError: If rails is not an integer or is a boolean.
        ValueError: If rails is not positive.
    """
    if isinstance(rails, bool) or not isinstance(rails, int):
        raise TypeError(
            f"rails must be an integer, got {type(rails).__name__}"
        )

    if rails <= 0:
        raise ValueError(
            f"rails must be a positive integer, got {rails}"
        )


def rail_fence_encrypt(plaintext: str, rails: int) -> str:
    """Encrypt plaintext using the Rail Fence cipher.

    Characters are distributed across rails in a zigzag pattern.
    The ciphertext is generated by concatenating the rails.

    All input characters are preserved, including spaces, punctuation,
    digits, and Unicode characters.

    Args:
        plaintext: Text to encrypt.
        rails: Positive number of rails.

    Returns:
        Encrypted ciphertext.

    Raises:
        TypeError: If plaintext is not a string or rails is not an integer.
        ValueError: If rails is not positive.

    Examples:
        >>> rail_fence_encrypt("WEAREDISCOVERED", 3)
        'WECRERDSOEEAIVD'

        >>> rail_fence_encrypt("HELLOWORLD", 2)
        'HLOOLELWRD'
    """
    # Step 1: Validate inputs.
    _validate_text(plaintext, "plaintext")
    _validate_rails(rails)

    # Step 2: Handle special cases.
    if not plaintext:
        return ""

    if rails == 1 or rails >= len(plaintext):
        return plaintext

    # Step 3: Create one list for each rail.
    rail_lists: list[list[str]] = [[] for _ in range(rails)]

    current_rail = 0
    direction = 1

    # Step 4: Distribute characters in a zigzag pattern.
    for char in plaintext:

        rail_lists[current_rail].append(char)

        # Reverse direction when reaching either boundary.
        if current_rail == 0:
            direction = 1
        elif current_rail == rails - 1:
            direction = -1

        current_rail += direction

    # Step 5: Concatenate all rails.
    ciphertext = "".join(
        "".join(rail) for rail in rail_lists
    )

    return ciphertext


def rail_fence_decrypt(ciphertext: str, rails: int) -> str:
    """Decrypt ciphertext using the Rail Fence cipher.

    The original zigzag pattern is reconstructed first. The ciphertext
    is then split into rail segments and read according to that pattern.

    All characters, including spaces, punctuation, digits, and Unicode
    characters, are preserved.

    Args:
        ciphertext: Text to decrypt.
        rails: Positive number of rails used during encryption.

    Returns:
        Recovered plaintext.

    Raises:
        TypeError: If ciphertext is not a string or rails is not an integer.
        ValueError: If rails is not positive.

    Examples:
        >>> rail_fence_decrypt("WECRERDSOEEAIVD", 3)
        'WEAREDISCOVERED'

        >>> rail_fence_decrypt("HLOOLELWRD", 2)
        'HELLOWORLD'
    """
    # Step 1: Validate inputs.
    _validate_text(ciphertext, "ciphertext")
    _validate_rails(rails)

    # Step 2: Handle special cases.
    if not ciphertext:
        return ""

    if rails == 1 or rails >= len(ciphertext):
        return ciphertext

    # Step 3: Reconstruct the original zigzag pattern.
    rail_pattern: list[int] = []
    rail_counts = [0] * rails

    current_rail = 0
    direction = 1

    for _ in range(len(ciphertext)):
        # Record the rail corresponding to this position.
        rail_pattern.append(current_rail)

        # Count characters belonging to this rail.
        rail_counts[current_rail] += 1

        # Change direction at the boundaries.
        if current_rail == 0:
            direction = 1
        elif current_rail == rails - 1:
            direction = -1

        current_rail += direction

    # Step 4: Split ciphertext into rail segments.
    rail_segments: list[str] = []

    start = 0

    for count in rail_counts:
        end = start + count

        rail_segments.append(ciphertext[start:end])

        start = end

    # Step 5: Initialize reading positions.
    rail_positions = [0] * rails

    plaintext_chars: list[str] = []

    # Step 6: Reconstruct plaintext.
    for rail in rail_pattern:
        char = rail_segments[rail][rail_positions[rail]]

        plaintext_chars.append(char)

        rail_positions[rail] += 1

    # Step 7: Join recovered characters.
    return "".join(plaintext_chars)


def columnar_encrypt(
    plaintext: str,
    key: Sequence[int],
) -> str:
    """Encrypt plaintext using Columnar Transposition.

    The plaintext is distributed across columns by writing characters
    row by row. Columns are then concatenated in the order specified
    by the permutation key.

    No padding is used. Incomplete final rows are handled naturally.
    All characters, including spaces, punctuation, digits, and Unicode,
    are preserved.

    Args:
        plaintext: Text to encrypt.
        key: Valid permutation describing the order in which columns
            are read. The key uses 1-based column numbering.

    Returns:
        Encrypted ciphertext.

    Raises:
        TypeError: If plaintext or key contains invalid types.
        ValueError: If key is not a valid permutation.

    Examples:
        >>> columnar_encrypt("ATTACKATDAWN", [3, 1, 4, 2])
        'TAWACDATNTKA'

        >>> columnar_encrypt("CRYPTOGRAPHY", [2, 4, 1, 3])
        'ROPPRYCTAYGH'
    """
    # Step 1: Validate inputs.
    _validate_text(plaintext, "plaintext")

    # Validate the permutation and obtain the number of columns.
    column_count = validate_permutation(key)

    # Step 2: Handle empty plaintext.
    if not plaintext:
        return ""

    # Step 3: Extract each original column.
    columns = [
        plaintext[column_index::column_count]
        for column_index in range(column_count)
    ]

    # Step 4: Read columns in the order specified by the key.
    ciphertext_parts = [
        columns[column_number - 1]
        for column_number in key
    ]

    # Step 5: Concatenate column contents.
    return "".join(ciphertext_parts)


def columnar_decrypt(
    ciphertext: str,
    key: Sequence[int],
) -> str:
    """Decrypt ciphertext using Columnar Transposition.

    No padding is assumed. The original column lengths are
    reconstructed from the ciphertext length and the key size.

    Args:
        ciphertext: Text to decrypt.
        key: Valid permutation describing the order in which
            the columns were read during encryption.

    Returns:
        Recovered plaintext.

    Raises:
        TypeError: If ciphertext or key contains invalid types.
        ValueError: If key is not a valid permutation.

    Examples:
        >>> columnar_decrypt("TAWACDATNTKA", [3, 1, 4, 2])
        'ATTACKATDAWN'

        >>> columnar_decrypt("ROPPRYCTAYGH", [2, 4, 1, 3])
        'CRYPTOGRAPHY'
    """
    # Step 1: Validate inputs and calculate the inverse permutation.
    _validate_text(ciphertext, "ciphertext")

    inverse_key = inverse_permutation(key)
    column_count = len(inverse_key)

    # Step 2: Handle empty ciphertext.
    if not ciphertext:
        return ""

    # Step 3: Calculate the original length of each column.
    quotient, remainder = divmod(
        len(ciphertext),
        column_count,
    )

    column_lengths = [
        quotient + (1 if index < remainder else 0)
        for index in range(column_count)
    ]

    # Step 4: Split ciphertext into segments in key order.
    segments = []
    cursor = 0

    for column_number in key:
        column_length = column_lengths[column_number - 1]

        segments.append(
            ciphertext[cursor:cursor + column_length]
        )

        cursor += column_length

    # Step 5: Restore original column order using inverse permutation.
    columns = [
        segments[position - 1]
        for position in inverse_key
    ]

    # Step 6: Read the reconstructed columns row by row.
    plaintext_chars = []
    row_count = quotient + (1 if remainder > 0 else 0)

    for row in range(row_count):
        for column_index in range(column_count):
            if row < len(columns[column_index]):
                plaintext_chars.append(
                    columns[column_index][row]
                )

    # Step 7: Join recovered characters.
    return "".join(plaintext_chars)


def double_columnar_encrypt(
    plaintext: str,
    key1: Sequence[int],
    key2: Sequence[int],
) -> str:
    """Encrypt plaintext using Double Columnar Transposition.

    The Columnar Transposition cipher is applied twice:
    first with key1, then with key2.

    No padding is used. All input characters are preserved.

    Args:
        plaintext: Text to encrypt.
        key1: First valid columnar permutation key.
        key2: Second valid columnar permutation key.

    Returns:
        Encrypted ciphertext.

    Raises:
        TypeError: If plaintext or either key has invalid types.
        ValueError: If either key is not a valid permutation.

    Examples:
        >>> double_columnar_encrypt(
        ...     "ATTACKATDAWN",
        ...     [3, 1, 4, 2],
        ...     [2, 3, 1],
        ... )
        'ACTKWDNATAAT'
    """
    # Step 1: Apply the first Columnar Transposition.
    intermediate = columnar_encrypt(plaintext, key1)

    # Step 2: Apply the second Columnar Transposition.
    ciphertext = columnar_encrypt(intermediate, key2)

    # Step 3: Return the final ciphertext.
    return ciphertext
