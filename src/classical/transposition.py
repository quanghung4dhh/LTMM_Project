
"""Classical transposition cipher implementations."""

from __future__ import annotations


def _validate_text(text: str, name: str) -> None:
    """Validate that the input text is a string.

    Args:
        text: Plaintext or ciphertext.
        name: Parameter name used in the error message.

    Raises:
        TypeError: If text is not a string.
    """
    if not isinstance(text, str):
        raise TypeError(
            f"{name} must be a string, got {type(text).__name__}"
        )


def _validate_rails(rails: int) -> None:
    """Validate the number of rails.

    Args:
        rails: Number of rails.

    Raises:
        TypeError: If rails is not an integer or is a boolean.
        ValueError: If rails is not positive.
    """
    if isinstance(rails, bool) or not isinstance(rails, int):
        raise TypeError(
            f"rails must be an integer, got {type(rails).__name__}"
        )

    if rails <= 0:
        raise ValueError(
            f"rails must be a positive integer, got {rails}"
        )


def rail_fence_encrypt(plaintext: str, rails: int) -> str:
    """Encrypt plaintext using the Rail Fence cipher.

    Characters are distributed across rails in a zigzag pattern.
    The ciphertext is generated by concatenating the rails.

    All input characters are preserved, including spaces, punctuation,
    digits, and Unicode characters.

    Args:
        plaintext: Text to encrypt.
        rails: Positive number of rails.

    Returns:
        Encrypted ciphertext.

    Raises:
        TypeError: If plaintext is not a string or rails is not an integer.
        ValueError: If rails is not positive.

    Examples:
        >>> rail_fence_encrypt("WEAREDISCOVERED", 3)
        'WECRERDSOEEAIVD'

        >>> rail_fence_encrypt("HELLOWORLD", 2)
        'HLOOLELWRD'
    """
    # Step 1: Validate inputs.
    _validate_text(plaintext, "plaintext")
    _validate_rails(rails)

    # Step 2: Handle special cases.
    if not plaintext:
        return ""

    if rails == 1 or rails >= len(plaintext):
        return plaintext

    # Step 3: Create one list for each rail.
    rail_lists: list[list[str]] = [[] for _ in range(rails)]

    current_rail = 0
    direction = 1

    # Step 4: Distribute characters in a zigzag pattern.
    for char in plaintext:

        rail_lists[current_rail].append(char)

        # Reverse direction when reaching either boundary.
        if current_rail == 0:
            direction = 1
        elif current_rail == rails - 1:
            direction = -1

        current_rail += direction

    # Step 5: Concatenate all rails.
    ciphertext = "".join(
        "".join(rail) for rail in rail_lists
    )

    return ciphertext
